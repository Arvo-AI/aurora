"""The committed snapshot set: five documents a LIVE capture wrote.

These fixtures are the review path. They are read from `fixtures/snapshots`,
never regenerated by the test, so a change in the checks that would flip a
verdict fails here instead of passing silently.
"""

from __future__ import annotations

import json
import subprocess
from pathlib import Path

import pytest

from verifier.contract import load_contract
from verifier.decision import CONFIRMED, INCONCLUSIVE, REJECTED, VERIFIED_WITHIN_CONTRACT
from verifier.observations import from_snapshot
from verifier.report import report_document, write_report
from verifier.snapshots import fixture_path, render_table, runs_of, verify

FIXTURES = Path(__file__).resolve().parents[1] / "fixtures" / "snapshots"
INCOMPLETE = Path(__file__).resolve().parent / "fixtures" / "snapshots" / "missing-pods.json"
CONTRACT = load_contract()
VARIANTS = tuple(CONTRACT.oracle.variants)
EXPECTED = {
    "baseline": None,
    "full": VERIFIED_WITHIN_CONTRACT,
    "p1_raise_limit": VERIFIED_WITHIN_CONTRACT,
    "partial_worker_only": REJECTED,
    "partial_frontend_only": REJECTED,
    "noop": REJECTED,
}


def test_the_expected_verdicts_cover_every_variant() -> None:
    assert tuple(EXPECTED) == VARIANTS


def test_the_set_holds_one_complete_fixture_per_variant() -> None:
    assert sorted(path.stem for path in FIXTURES.glob("*.json")) == sorted(VARIANTS)
    contract = CONTRACT
    for name in VARIANTS:
        observations = from_snapshot(fixture_path(FIXTURES, name))
        assert observations.is_complete, observations.missing_metadata
        assert observations.meta.variant == name
        assert observations.meta.provenance == "LIVE"
        assert observations.meta.lab_commit == contract.source.commit


def test_the_set_reaches_the_verdicts_the_contract_promises() -> None:
    attempts = verify(CONTRACT, FIXTURES)
    assert [attempt.variant for attempt in attempts] == list(VARIANTS)
    assert attempts[0].verdict.reproduction_status == CONFIRMED
    for attempt in attempts:
        expected = EXPECTED[attempt.variant]
        if expected is not None:
            assert attempt.verdict.status == expected, attempt.variant


def test_every_fixture_supports_all_six_checks_with_evidence() -> None:
    for attempt in verify(CONTRACT, FIXTURES):
        assert len(attempt.verdict.results) == 6
        for result in attempt.verdict.results:
            assert result.evidence, f"{attempt.variant}/{result.id} has no evidence"


def test_the_table_names_the_two_parts_of_the_table() -> None:
    text = render_table(runs_of(verify(CONTRACT, FIXTURES)))
    for name in VARIANTS:
        assert name in text
    assert "0/6 pass" in text
    assert "6/6 pass" in text
    assert "baseline: CONFIRMED" in text


def test_the_committed_set_reaches_every_verdict_without_a_process(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Same negative test as the simulated set, over the committed documents.

    The patch lasts for this test only, and the undo proves it.
    """
    original = subprocess.run

    def forbidden(*args: object, **kwargs: object) -> None:
        raise AssertionError("the snapshot set started a subprocess")

    monkeypatch.setattr(subprocess, "run", forbidden)
    assert len(verify(CONTRACT, FIXTURES)) == len(VARIANTS)
    monkeypatch.undo()
    assert subprocess.run is original


def test_a_capture_missing_a_section_is_inconclusive(tmp_path: Path) -> None:
    directory = tmp_path / "set"
    directory.mkdir()
    for name in VARIANTS:
        source = fixture_path(FIXTURES, name)
        (directory / source.name).write_bytes(source.read_bytes())
    (directory / "full.json").write_text(INCOMPLETE.read_text(encoding="utf-8"), encoding="utf-8")

    assert "pods" in from_snapshot(directory / "full.json").missing_metadata
    attempts = verify(load_contract(), directory)
    assert attempts[1].verdict.status == INCONCLUSIVE
    assert {result.status for result in attempts[1].verdict.results} == {INCONCLUSIVE}


def test_the_report_from_the_committed_set_is_deterministic(tmp_path: Path) -> None:
    contract = load_contract()
    runs = runs_of(verify(contract, FIXTURES))
    first = write_report(
        contract, runs, tmp_path / "first.json", generated_at="2026-11-16T00:00:00Z"
    )
    second = write_report(
        contract, runs, tmp_path / "second.json", generated_at="2026-11-16T00:00:00Z"
    )
    assert first.read_bytes() == second.read_bytes()
    document = report_document(contract, runs, generated_at="2026-11-16T00:00:00Z")
    assert document["advisory"] is True
    assert document["mode"] == "SNAPSHOT"


def test_the_fixtures_are_json_with_sorted_keys() -> None:
    for name in VARIANTS:
        path = fixture_path(FIXTURES, name)
        text = path.read_text(encoding="utf-8")
        assert text.endswith("\n")
        document = json.loads(text)
        assert list(document) == sorted(document)
